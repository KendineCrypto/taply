/** Contract panic codes from ABI.md. Only these are ever surfaced from an RPC error. */
export const CONTRACT_ERROR_CODES = [
  "NONCE_CONSUMED", "REQUEST_ID_MISMATCH", "TERMS_HASH_MISMATCH", "REQUEST_NOT_FOUND",
  "EXACT_STORAGE_DEPOSIT_REQUIRED", "STALE_QUOTE", "STORAGE_QUOTE_MISMATCH", "STORAGE_GROWTH_FORBIDDEN",
  "EXACT_PRINCIPAL_REQUIRED", "ONE_YOCTO_REQUIRED", "DIRECT_WALLET_ONLY", "RECIPIENT_ONLY", "WRONG_PAYER",
  "NOT_OPEN", "FUNDING_EXPIRED", "INVALID_FUNDING_EXPIRY", "NO_RECORDED_TRANSFER_FAILURE",
  "OPERATION_NONCE_MISMATCH", "PRIVATE_CALLBACK", "WRONG_OPERATION_KIND", "STALE_CALLBACK",
  "UNKNOWN_PROMISE_RESULT", "INSUFFICIENT_PREPAID_GAS", "INSUFFICIENT_OPERATIONAL_LIQUIDITY",
  "ACCOUNTING_OVERFLOW", "ACCOUNTING_UNDERFLOW", "COUNTER_OVERFLOW", "CONSERVATION_FAILURE",
  "INVALID_ARGUMENTS", "INPUT_TOO_LARGE", "INVALID_HASH", "NONCANONICAL_DECIMAL", "U64_OVERFLOW",
  "U128_OVERFLOW", "ZERO_AMOUNT", "MEMO_TOO_LONG", "UNSUPPORTED_SCHEMA", "WRONG_NETWORK",
  "WRONG_CONTRACT", "SELF_RECIPIENT", "TOKEN_DISABLED", "PROTECTED_DISABLED", "HANDSHAKE_DISABLED",
] as const;
export type ContractErrorCode = typeof CONTRACT_ERROR_CODES[number];

/** Finds a known code token in untrusted RPC error text. The text itself is discarded. */
export function extractContractErrorCode(text: string): ContractErrorCode | null {
  for (const token of text.slice(0, 4096).match(/[A-Z][A-Z0-9_]{2,40}/g) ?? []) {
    if ((CONTRACT_ERROR_CODES as readonly string[]).includes(token)) return token as ContractErrorCode;
  }
  return null;
}
